import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
await mkdir('.impeccable/review',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[];
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4328/');
await page.evaluate(async()=>{await document.fonts.ready; await Promise.all(Array.from(document.images).map(img=>{img.loading='eager'; return img.decode().catch(()=>{});}));});
await page.screenshot({path:'.impeccable/review/desktop.png',fullPage:true});
await page.locator('[data-open="lago"]').click();
await page.screenshot({path:'.impeccable/review/planner-desktop.png'});
await page.locator('[data-close="stay-dialog"]').click();
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:4328/');
await page.evaluate(async()=>{await document.fonts.ready; await Promise.all(Array.from(document.images).map(img=>{img.loading='eager'; return img.decode().catch(()=>{});}));});
await page.screenshot({path:'.impeccable/review/mobile.png',fullPage:true});
await page.locator('[data-open="lago"]').click();
await page.screenshot({path:'.impeccable/review/planner-mobile.png'});
await page.locator('#save-plan').scrollIntoViewIfNeeded();
await page.screenshot({path:'.impeccable/review/planner-mobile-quote.png'});
await page.locator('[data-close="stay-dialog"]').click();
await page.setViewportSize({width:320,height:800});
await page.goto('http://127.0.0.1:4328/');
await page.evaluate(async()=>{await document.fonts.ready; await Promise.all(Array.from(document.images).map(img=>{img.loading='eager';return img.decode().catch(()=>{});}));});
await page.screenshot({path:'.impeccable/review/mobile-small.png',fullPage:true});
await writeFile('.impeccable/review/console.json',JSON.stringify(errors,null,2));
console.log('Screenshots captured; console errors: '+errors.length);
await browser.close();


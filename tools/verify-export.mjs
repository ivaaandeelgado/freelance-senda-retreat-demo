import {chromium} from '@playwright/test';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
import {writeFile,mkdir} from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const errors=[],remote=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(/^https?:/.test(r.url()))remote.push(r.url());});
await page.goto(pathToFileURL(path.resolve('exports/Senda-OpenDesign.html')).href);
await page.evaluate(async()=>{await document.fonts.ready;await Promise.all(Array.from(document.images).map(img=>{img.loading='eager';return img.decode();}));});
assert.equal(await page.locator('.stay-card').count(),6);
await page.locator('[data-scene="mar"]').click();
await page.locator('#hero-image').evaluate(img=>img.decode());
assert.equal(await page.locator('.stay-card').count(),2);
await page.locator('[data-filter="all"]').click();
await page.locator('[data-open="lago"]').click();
await page.locator('#book-breakfast').check();
assert.equal(await page.locator('#save-plan').isEnabled(),true);
await page.locator('#save-plan').click();
assert.equal(await page.locator('#plan-dialog').isVisible(),true);
assert.equal(await page.locator('#plan-content h3').textContent(),'El refugio del lago');
assert.deepEqual(errors,[]);assert.deepEqual(remote,[]);
await mkdir('evidence',{recursive:true});
await writeFile('evidence/portable-export.json',JSON.stringify({testedAt:new Date().toISOString(),source:'exports/Senda-OpenDesign.html',protocol:'file:',passed:true,checks:['all local assets decoded','six stays rendered','landscape switch','quoted stay saved','no JavaScript errors','no HTTP requests'],errors,remote},null,2));
console.log('Portable HTML verified over file:; no external requests; planner works.');
await browser.close();

import {chromium} from '@playwright/test';
import {todayISO,addDays} from '../public/js/domain.js';
import {writeFile} from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const root='.impeccable/review/';
await page.goto('http://127.0.0.1:4328/');
await page.evaluate(()=>document.fonts.ready);
await page.locator('[data-scene="mar"]').click();
await page.locator('#hero-image').evaluate(img=>img.decode());
await page.screenshot({path:root+'scene-coast.png'});
await page.locator('[data-filter="bosque"]').click();await page.locator('#pets').check();
await page.locator('#empty-state').scrollIntoViewIfNeeded();
await page.screenshot({path:root+'empty-state.png'});
await page.locator('#reset-filters').click();await page.locator('[data-open="lago"]').click();
await page.locator('#book-checkin').fill(addDays(todayISO(),12));await page.locator('#book-checkout').fill(addDays(todayISO(),14));
await page.screenshot({path:root+'date-error.png'});
await page.locator('#book-checkin').fill(addDays(todayISO(),1));await page.locator('#book-checkout').fill(addDays(todayISO(),4));
await page.locator('#book-breakfast').check();await page.locator('#save-plan').click();
await page.screenshot({path:root+'saved-plan.png'});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:root+'saved-plan-mobile.png'});
await page.locator('[data-close="plan-dialog"]').click();
await page.goto('http://127.0.0.1:4328/');
await page.locator('#privacy-button').click();
await page.screenshot({path:root+'privacy-mobile.png'});
await writeFile(root+'interaction-evidence.json',JSON.stringify({created:new Date().toISOString(),viewports:[1440,390,320],tests:'evidence/browser-tests.json',motion:'scene clip-path transition 600ms; disabled under prefers-reduced-motion',screenshots:['scene-coast','empty-state','date-error','saved-plan','saved-plan-mobile','privacy-mobile']},null,2));
await browser.close();

